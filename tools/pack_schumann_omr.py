"""Package recorded Schumann outputs as a separate notebook data file.

Run after updating sessions/02-building-an-edition/teacher/references/omr-schumann/:
    python tools/pack_schumann_omr.py
Then rebuild notebooks. Source images, models, executed notebooks and compressed
original logs stay outside the ZIP. Logs remain in the reference folder.
"""

import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "sessions/02-building-an-edition/teacher/references/omr-schumann"
TARGET = ROOT / "sessions/02-building-an-edition/notebooks/schumann-omr-recordings.zip"
HELPER = ROOT / "tools/notebooks/helpers/omr_recordings.py"
ALLOWED = {".json", ".musicxml", ".mei", ".svg", ".log", ".txt", ".md"}


def main():
    files = [p for p in sorted(SOURCE.rglob("*")) if p.is_file()
             and (p.suffix in ALLOWED or p.name == "LICENSE") and p.name != "manifest.json"]
    manifest_path = SOURCE / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files_sha256"] = {p.relative_to(SOURCE).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                                for p in files}
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(TARGET, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in sorted(files + [manifest_path]):
            entry = zipfile.ZipInfo(path.relative_to(SOURCE).as_posix(), date_time=(2026, 10, 24, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(entry, path.read_bytes())
    digest = hashlib.sha256(TARGET.read_bytes()).hexdigest()
    HELPER.write_text('''"""Load the separate Schumann recordings ZIP; generated by the packaging tool."""

import hashlib
from pathlib import Path
import zipfile

SCHUMANN_RECORDINGS_FILE = "schumann-omr-recordings.zip"
SCHUMANN_RECORDINGS_SHA256 = "''' + digest + '''"


def find_schumann_recordings(start=None):
    """Find the ZIP beside a downloaded notebook or in the course checkout."""
    start = Path(start or Path.cwd()).resolve()
    for folder in (start, *start.parents):
        for candidate in (folder / SCHUMANN_RECORDINGS_FILE,
                          folder / "notebooks" / SCHUMANN_RECORDINGS_FILE,
                          folder / "sessions/02-building-an-edition/notebooks" / SCHUMANN_RECORDINGS_FILE):
            if candidate.is_file():
                return candidate
    raise FileNotFoundError(
        "Copy schumann-omr-recordings.zip beside this notebook, or run get_notebooks.py "
        "to download both notebook and data. No recognition installation is needed.")


def unpack_schumann_recordings(bundle, destination):
    """Verify the data file and unpack it without replacing edited files."""
    bundle, destination = Path(bundle), Path(destination).resolve()
    if hashlib.sha256(bundle.read_bytes()).hexdigest() != SCHUMANN_RECORDINGS_SHA256:
        raise ValueError("Recording ZIP differs from this notebook. Download a matching pair.")
    with zipfile.ZipFile(bundle) as archive:
        entries = [((destination / name).resolve(), archive.read(name)) for name in archive.namelist()]
    for path, content in entries:
        if not path.is_relative_to(destination):
            raise ValueError("Unexpected archive path")
        if path.exists() and path.read_bytes() != content:
            raise FileExistsError(f"Preserving edited file: {path}. Choose a new WORK folder.")
    for path, content in entries:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():
            path.write_bytes(content)
    return destination
''', encoding="utf-8")
    print(f"Saved {TARGET.stat().st_size:,} bytes to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
